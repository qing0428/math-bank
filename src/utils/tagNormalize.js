// ─── 归一化函数 ─────────────────────────────────────────────

/**
 * 核心：将任意标签归一化为标准标签。
 *
 * 流程：
 * 1. 精确匹配同义词表
 * 2. 检查是否已在标准标签库中
 * 3. 匹配性归一化（标准标签是输入标签的子串）
 * 4. 无法归一化则原样返回（保留，不丢失信息）
 */
export function normalizeTag(tag) {
  if (!tag || typeof tag !== 'string') return ''
  const trimmed = tag.trim()
  if (!trimmed) return ''

  // 1. 精确匹配同义词表
  const canonical = SYNONYM_MAP[trimmed]
  if (canonical) return canonical

  // 2. 已在标准标签库中
  if (isStandardTag(trimmed)) return trimmed

  // 3. 匹配性归一化：遍历标准标签，找到最短的标准标签是输入的子串
  //    例如 "复式条形统计图" → 标准库中有 "条形统计图"，且 "条形统计图" 是 "复式条形统计图" 的子串
  const allStandard = getAllStandardTags()
  // 按长度降序排列，优先匹配更长的标准标签
  const candidates = allStandard
    .filter(std => trimmed.includes(std) || std.includes(trimmed))
    .sort((a, b) => b.length - a.length)

  if (candidates.length > 0) {
    // 如果标准标签是输入的子串，返回标准标签
    // 如果输入是标准标签的子串，也返回标准标签（更完整的版本）
    return candidates[0]
  }

  // 4. 无法归一化，原样返回
  return trimmed
}

/**
 * 批量归一化标签数组。
 */
export function normalizeTags(tags) {
  if (!Array.isArray(tags)) return []
  const normalized = tags.map(normalizeTag).filter(Boolean)
  // 去重
  return [...new Set(normalized)]
}

/**
 * 检查标签是否在标准库中。
 */
export function isStandardTag(tag) {
  return getAllStandardTags().includes(tag)
}

/**
 * 获取所有标准标签的扁平列表。
 */
export function getAllStandardTags() {
  return [
    ...STANDARD_TAGS.common,
    ...STANDARD_TAGS.primary,
    ...STANDARD_TAGS.middle,
    ...STANDARD_TAGS.high,
  ]
}

/**
 * 获取标准标签库（按分类）。
 */
export function getStandardTagsByCategory() {
  return STANDARD_TAGS
}

/**
 * 为 AI 打标生成标准标签提示。
 * 根据年级返回适用的标准标签列表。
 */
export function getTagPromptHint(grade) {
  const all = [...STANDARD_TAGS.common]
  if (!grade) {
    all.push(...STANDARD_TAGS.primary, ...STANDARD_TAGS.middle, ...STANDARD_TAGS.high)
  } else if (/^[一二三]年级/.test(grade)) {
    all.push(...STANDARD_TAGS.primary)
  } else if (/^[四五六]年级/.test(grade)) {
    all.push(...STANDARD_TAGS.primary)
  } else if (/七|八|九|初[一二三]/.test(grade)) {
    all.push(...STANDARD_TAGS.middle)
  } else if (/高[一二三]/.test(grade)) {
    all.push(...STANDARD_TAGS.high)
  }
  return all
}
